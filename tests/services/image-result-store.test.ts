import assert from 'node:assert/strict'
import test from 'node:test'

import {
  ImageResultStore,
  ImageResultStoreError
} from '../../src/main/services/image-result-store.ts'

const PNG = Buffer.concat([
  Buffer.from('89504e470d0a1a0a', 'hex'),
  Buffer.from('generated-image-test')
])

function image(bytes = PNG) {
  return {
    mimeType: 'image/png' as const,
    dataUrl: `data:image/png;base64,${bytes.toString('base64')}`
  }
}

test('stores generated bytes behind owner-bound one-shot tokens', () => {
  const store = new ImageResultStore()
  const refs = store.issueMany([image()], 7)
  assert.equal(refs.length, 1)
  assert.match(refs[0]!.imageToken, /^img_[A-Za-z0-9_-]{43}$/)
  assert.equal(refs[0]!.byteLength, PNG.length)
  assert.equal(store.consume(refs[0]!.imageToken, 8), null)
  const consumed = store.consume(refs[0]!.imageToken, 7)
  assert.deepEqual(consumed, {
    mimeType: 'image/png',
    byteLength: PNG.length,
    dataBase64: PNG.toString('base64')
  })
  assert.equal(store.consume(refs[0]!.imageToken, 7), null)
})

test('expires, revokes, validates, and bounds generated image memory', () => {
  let now = 1_000
  const store = new ImageResultStore({
    now: () => now,
    tokenLifetimeMs: 1_000,
    maxRecords: 2,
    maxStoredBytes: PNG.length * 2
  })
  const [first] = store.issueMany([image()], 1)
  now = 2_000
  assert.equal(store.consume(first!.imageToken, 1), null)

  const refs = store.issueMany([image(), image()], 1)
  assert.throws(
    () => store.issueMany([image()], 1),
    (error: unknown) => error instanceof ImageResultStoreError && error.code === 'capacity_exceeded'
  )
  store.revokeOwner(1)
  assert.equal(store.consume(refs[0]!.imageToken, 1), null)
  assert.equal(store.consume(refs[1]!.imageToken, 1), null)

  for (const invalid of [
    { mimeType: 'image/svg+xml', dataUrl: 'data:image/svg+xml;base64,PHN2Zz4=' },
    { mimeType: 'image/png', dataUrl: 'data:image/png;base64,not-canonical' },
    { mimeType: 'image/png', dataUrl: `data:image/png;base64,${Buffer.from('not png').toString('base64')}` }
  ]) {
    assert.throws(
      () => store.issueMany([invalid as never], 1),
      (error: unknown) => error instanceof ImageResultStoreError && error.code === 'invalid_image'
    )
  }
})
